// Cut the North Atlantic out of Natural Earth 1:50m land and lakes (public domain) and
// write the rings the fork plate draws.
//
//   node scripts/atlantic-coast.mjs ne_50m_land.geojson ne_50m_lakes.geojson > src/atlanticCoast.ts
import { readFileSync } from "node:fs";

const WINDOW = { west: -125, east: 30, south: 0, north: 85 };
const TOLERANCE_DEG = 0.035;

function rings(file) {
  const out = [];
  for (const feature of JSON.parse(readFileSync(file, "utf8")).features) {
    const { type, coordinates } = feature.geometry;
    const polygons = type === "Polygon" ? [coordinates] : coordinates;
    for (const polygon of polygons) {
      out.push(...polygon);
    }
  }
  return out;
}

// Sutherland-Hodgman against one half-plane at a time.
function clip(ring, inside, cross) {
  const out = [];
  for (let index = 0; index < ring.length; index += 1) {
    const a = ring[index];
    const b = ring[(index + 1) % ring.length];
    if (inside(b)) {
      if (!inside(a)) out.push(cross(a, b));
      out.push(b);
    } else if (inside(a)) {
      out.push(cross(a, b));
    }
  }
  return out;
}

function clipToWindow(ring) {
  const edges = [
    [
      ([x]) => x >= WINDOW.west,
      (a, b) => [WINDOW.west, a[1] + ((b[1] - a[1]) * (WINDOW.west - a[0])) / (b[0] - a[0])],
    ],
    [
      ([x]) => x <= WINDOW.east,
      (a, b) => [WINDOW.east, a[1] + ((b[1] - a[1]) * (WINDOW.east - a[0])) / (b[0] - a[0])],
    ],
    [
      ([, y]) => y >= WINDOW.south,
      (a, b) => [a[0] + ((b[0] - a[0]) * (WINDOW.south - a[1])) / (b[1] - a[1]), WINDOW.south],
    ],
    [
      ([, y]) => y <= WINDOW.north,
      (a, b) => [a[0] + ((b[0] - a[0]) * (WINDOW.north - a[1])) / (b[1] - a[1]), WINDOW.north],
    ],
  ];
  let current = ring;
  for (const [inside, cross] of edges) {
    if (current.length === 0) return [];
    current = clip(current, inside, cross);
  }
  return current;
}

function distance(point, a, b) {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const length = dx * dx + dy * dy;
  const t =
    length === 0
      ? 0
      : Math.max(0, Math.min(1, ((point[0] - a[0]) * dx + (point[1] - a[1]) * dy) / length));
  return Math.hypot(point[0] - (a[0] + t * dx), point[1] - (a[1] + t * dy));
}

function simplify(points) {
  if (points.length < 3) return points;
  let worst = 0;
  let at = 0;
  for (let index = 1; index < points.length - 1; index += 1) {
    const d = distance(points[index], points[0], points[points.length - 1]);
    if (d > worst) {
      worst = d;
      at = index;
    }
  }
  if (worst <= TOLERANCE_DEG) return [points[0], points[points.length - 1]];
  return [...simplify(points.slice(0, at + 1)).slice(0, -1), ...simplify(points.slice(at))];
}

const kept = [];
for (const file of process.argv.slice(2)) {
  for (const ring of rings(file)) {
    const clipped = clipToWindow(ring);
    if (clipped.length < 4) continue;
    const reduced = simplify([...clipped, clipped[0]]);
    if (reduced.length < 4) continue;
    kept.push(reduced.flatMap(([x, y]) => [Number(x.toFixed(2)), Number(y.toFixed(2))]));
  }
}

console.log(`/**
 * Natural Earth 1:50m land and lakes (public domain), cut to the North Atlantic and
 * simplified to 0.035 degrees. Each ring is a flat list of longitude, latitude pairs;
 * lake rings sit inside land rings, so an even-odd fill leaves them as water.
 * Generated by scripts/atlantic-coast.mjs.
 */
export const ATLANTIC_COAST: readonly (readonly number[])[] = ${JSON.stringify(kept)};`);
