from datetime import UTC, datetime
from typing import TYPE_CHECKING

import numpy as np
import xarray as xr
from weathernext.utils.data_utils import extract_inputs_targets_forcings

from stormfork.grid import LEVELS_HPA, STEP
from stormfork.ic.layout import STATIC_NAMES, SampleStatics, coarsen

if TYPE_CHECKING:
    from numpy.typing import NDArray

ATMOSPHERE = (
    "temperature",
    "geopotential",
    "u_component_of_wind",
    "v_component_of_wind",
    "vertical_velocity",
    "specific_humidity",
)
SURFACE = (
    "2m_temperature",
    "mean_sea_level_pressure",
    "10m_u_component_of_wind",
    "10m_v_component_of_wind",
    "sea_surface_temperature",
)

HUMIDITY = "specific_humidity"
FORCINGS = ("year_progress_sin", "year_progress_cos", "day_progress_sin", "day_progress_cos")
CYCLONE_TARGETS = (
    "cyclone_exists_gaussian_unit_mode",
    "cyclone_all_wind_disc",
    "cyclone_usa_wind_disc",
    *(
        f"cyclone_usa_r{radius}_{quadrant}_radius_disc"
        for radius in (34, 50, 64)
        for quadrant in ("ne", "se", "sw", "nw")
    ),
    "cyclone_usa_rmw_disc",
    "cyclone_usa_pres_disc",
)
TARGETS = ATMOSPHERE + SURFACE + ("total_precipitation_6hr",) + CYCLONE_TARGETS


def frame_times(init: datetime, num_steps: int = 40) -> "NDArray[np.datetime64]":
    """The two input frames' and every target frame's times, from init minus six hours.

    Naive initialization times are interpreted as UTC.

    Raises:
        ValueError: The forecast has no steps or initialization is off the six-hour cycle.
    """
    if num_steps < 1:
        msg = "num_steps must be positive"
        raise ValueError(msg)
    utc_init = init.replace(tzinfo=UTC) if init.tzinfo is None else init.astimezone(UTC)
    if utc_init.hour % 6 or utc_init.minute or utc_init.second or utc_init.microsecond:
        msg = "Initialization must fall on a six-hour UTC cycle"
        raise ValueError(msg)
    init_time = np.datetime64(utc_init.replace(tzinfo=None), "ns")
    return init_time + np.arange(-1, num_steps + 1) * np.timedelta64(STEP, "ns")


def build_input(
    init: datetime, store: xr.Dataset, num_steps: int = 40, *, statics: SampleStatics
) -> xr.Dataset:
    """Build two ERA5 input frames and NaN targets with explicit sample statics.

    The store uses ARCO's long variable names and time/level/latitude/longitude
    coordinates. Naive initialization times are interpreted as UTC.

    Raises:
        ValueError: The forecast has no steps or initialization is off the six-hour cycle.
    """
    dates = frame_times(init, num_steps)
    selected = store[list(ATMOSPHERE + SURFACE)].sel(time=dates[:2], level=list(LEVELS_HPA))
    selected = selected.rename({"latitude": "lat", "longitude": "lon"})
    return lay_out(coarsen(selected), dates, statics=statics)


def lay_out(
    frames: xr.Dataset, dates: "NDArray[np.datetime64]", *, statics: SampleStatics
) -> xr.Dataset:
    """Lay two one-degree input frames out as model input, with NaN targets after them.

    frames holds the atmosphere and surface fields at the first two of dates,
    which frame_times gives. Specific humidity is clipped at zero. Forcings are
    generated by the pinned model's extraction routine.
    """
    step = np.timedelta64(STEP, "ns")
    num_steps = dates.size - 2
    values = {
        name: np.asarray(frames[name].values, dtype=np.float32) for name in ATMOSPHERE + SURFACE
    }
    # ERA5 holds a few slightly negative humidities. Every edit clips them, and
    # the edit check requires none, so every run starts from the clipped state.
    values[HUMIDITY] = np.maximum(values[HUMIDITY], 0)
    selected = xr.Dataset(
        {name: xr.DataArray(field, dims=frames[name].dims) for name, field in values.items()},
        coords={
            "time": np.arange(2) * step,
            "level": np.array(LEVELS_HPA, dtype=np.int32),
            "lat": np.asarray(frames.lat.values, dtype=np.float32),
            "lon": np.asarray(frames.lon.values, dtype=np.float32),
        },
    )
    result = selected.reindex(time=np.arange(num_steps + 2) * step).expand_dims(batch=1)
    result = result.transpose("batch", "time", "level", "lat", "lon", missing_dims="ignore")
    result.coords["datetime"] = (("batch", "time"), dates[None, :])
    for name in TARGETS:
        if name not in result:
            result[name] = xr.DataArray(
                np.broadcast_to(
                    np.float32(np.nan), (1, num_steps + 2, result.sizes["lat"], result.sizes["lon"])
                ),
                dims=("batch", "time", "lat", "lon"),
            )
    for name, field in zip(
        STATIC_NAMES, (statics.geopotential_at_surface, statics.land_sea_mask), strict=True
    ):
        result[name] = field.copy(deep=True)
    result["seconds_since_epoch"] = xr.DataArray(
        dates.astype("datetime64[s]").astype(np.int64)[None, :], dims=("batch", "time")
    )
    inputs, _, forcings = extract_inputs_targets_forcings(
        result,
        input_variables=ATMOSPHERE + SURFACE + STATIC_NAMES + FORCINGS,
        target_variables=TARGETS,
        forcing_variables=FORCINGS,
        pressure_levels=LEVELS_HPA,
        input_duration="12h",
        target_lead_times=slice(STEP, num_steps * STEP),
    )
    # Extraction shifts the time origin to init; restore the sample's first-frame origin.
    for name in FORCINGS:
        values = np.concatenate([inputs[name].values, forcings[name].values], axis=1)
        result[name] = xr.DataArray(values, dims=inputs[name].dims)
    return result
